// Fills the Quran story cards with translations in every locale the app speaks.
//
// These are NOT written by us. Rendering a verse into another language is a
// translation of scripture, so each locale takes an established edition and the
// attribution below travels with the text. Run:
//
//   node scripts/gen-quran-translations.mjs
//
// Output: packages/core/src/content/quranTranslations.generated.ts
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const postsDir = path.join(root, 'packages/core/src/content/posts');
const out = path.join(root, 'packages/core/src/content/quranTranslations.generated.ts');

const CDN = 'https://cdn.jsdelivr.net/gh/fawazahmed0/quran-api@1/editions';

/**
 * One established edition per locale, chosen for being the recognised
 * translation in that language rather than the first one available.
 * `en` is absent on purpose: the cards already carry Saheeh International.
 */
const EDITIONS = {
  fr: { id: 'fra-muhammadhamidul', credit: 'Muhammad Hamidullah' },
  id: { id: 'ind-indonesianislam', credit: 'Kementerian Agama Republik Indonesia' },
  ms: { id: 'msa-abdullahmuhamma', credit: 'Abdullah Muhammad Basmeih' },
  th: { id: 'tha-kingfahadquranc', credit: 'King Fahd Complex' },
  ur: { id: 'urd-fatehmuhammadja', credit: 'Fateh Muhammad Jalandhry' },
};

/** Pulls `surah:ayah` or `surah:from-to` out of a post's source reference. */
function referenceOf(body) {
  const source = body.indexOf('source:');
  if (source === -1) return null;
  const m = /(\d+):(\d+)(?:\s*-\s*(\d+))?/.exec(body.slice(source));
  if (!m) return null;
  const chapter = Number(m[1]);
  const from = Number(m[2]);
  const to = m[3] ? Number(m[3]) : from;
  if (!chapter || !from || to < from) return null;
  return { chapter, from, to };
}

function quranPosts() {
  const found = [];
  for (const file of fs.readdirSync(postsDir).filter((f) => f.endsWith('.ts'))) {
    const text = fs.readFileSync(path.join(postsDir, file), 'utf8');
    for (const m of text.matchAll(/\{\s*id: '([^']+)',([\s\S]*?)\n {2}\},/g)) {
      const [, id, body] = m;
      if (!/kind: 'quran'/.test(body)) continue;
      const ref = referenceOf(body);
      if (ref) found.push({ id, ...ref });
      else console.warn(`  no reference found for ${id} (${file})`);
    }
  }
  return found;
}

async function fetchEdition(name) {
  const res = await fetch(`${CDN}/${name}.min.json`);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const json = await res.json();
  const byRef = new Map();
  for (const v of json.quran) byRef.set(`${v.chapter}:${v.verse}`, v.text.trim());
  return byRef;
}

const posts = quranPosts();
console.log(`Quran cards with a usable reference: ${posts.length}`);

const translations = {};
for (const [locale, edition] of Object.entries(EDITIONS)) {
  process.stdout.write(`  ${locale} ${edition.id} … `);
  const verses = await fetchEdition(edition.id);
  let filled = 0;
  for (const post of posts) {
    const parts = [];
    for (let v = post.from; v <= post.to; v++) {
      const text = verses.get(`${post.chapter}:${v}`);
      if (text) parts.push(text);
    }
    if (parts.length !== post.to - post.from + 1) continue;
    (translations[post.id] ??= {})[locale] = parts.join(' ');
    filled++;
  }
  console.log(`${filled}/${posts.length}`);
}

const complete = Object.values(translations).filter(
  (t) => Object.keys(t).length === Object.keys(EDITIONS).length,
).length;

const body = `/**
 * Quran translations for the story cards, one established edition per locale.
 * Generated by scripts/gen-quran-translations.mjs — do not edit by hand.
 *
 * These renderings are not ours. Each is an existing, named translation, and
 * QURAN_TRANSLATION_CREDITS below is what has to be shown wherever they are.
 */
import type { Locale } from '../types';

export const QURAN_TRANSLATION_CREDITS: Partial<Record<Locale, string>> = ${JSON.stringify(
  Object.fromEntries(Object.entries(EDITIONS).map(([l, e]) => [l, e.credit])),
  null,
  2,
)};

/** Card id to its translation in each locale. */
export const QURAN_TRANSLATIONS: Record<string, Partial<Record<Locale, string>>> = ${JSON.stringify(
  translations,
  null,
  2,
)};
`;

fs.writeFileSync(out, body, 'utf8');
console.log(`\nCards covered in every locale: ${complete}/${posts.length}`);
console.log(`Written: ${path.relative(root, out)}`);
